    def load_promoted(self, tenant_id: str, algorithm: str) -> LoadedModel:
        """
        Load the promoted (production) model for *algorithm* belonging to
        *tenant_id*.  Caches in memory; subsequent calls return the cached
        version unless the promoted model has changed.

        Raises:
            RuntimeError: No promoted model exists for this tenant + algorithm.
        """
        self._validate_tenant(tenant_id)
        cache_key = (tenant_id, algorithm)

        with self._lock:
            registry = self._get_registry(tenant_id)

            # Return cached if still the promoted version
            cached = self._loaded.get(cache_key)
            if cached:
                current = registry.get_promoted(algorithm)
                if current and current.model_id == cached.model_id:
                    log.debug(
                        "Cache hit | tenant=%s algo=%s id=%s",
                        tenant_id, algorithm, cached.model_id,
                    )
                    return cached

            record = registry.get_promoted(algorithm)
            if not record:
                raise RuntimeError(
                    f"No promoted model found for tenant='{tenant_id}' "
                    f"algorithm='{algorithm}'. Train and promote a model first."
                )
            return self._load_record(tenant_id, record, registry)

    def load_by_id(self, tenant_id: str, model_id: str) -> LoadedModel:
        """
        Load a specific model by its registry ID, scoped to *tenant_id*.

        Raises:
            KeyError: model_id not found in this tenant's registry.
        """
        self._validate_tenant(tenant_id)

        with self._lock:
            registry = self._get_registry(tenant_id)

            # Return cached copy if already warm for this tenant
            for key, lm in self._loaded.items():
                if key[0] == tenant_id and lm.model_id == model_id:
                    return lm

            record = registry.get(model_id)
            if not record:
                raise KeyError(
                    f"Model ID '{model_id}' not found in registry for "
                    f"tenant='{tenant_id}'."
                )
            return self._load_record(tenant_id, record, registry)

    def reload(self, tenant_id: str, algorithm: str) -> LoadedModel:
        """
        Force-reload the promoted model for *tenant_id* + *algorithm*.
        Call this after a new model is promoted without restarting the server.
        """
        self._validate_tenant(tenant_id)
        with self._lock:
            self._loaded.pop((tenant_id, algorithm), None)
        return self.load_promoted(tenant_id, algorithm)

    def unload(self, tenant_id: str, algorithm: str) -> None:
        """
        Remove a tenant's model from memory.
        Has no effect on the same algorithm loaded for other tenants.
        """
        self._validate_tenant(tenant_id)
        with self._lock:
            dropped = self._loaded.pop((tenant_id, algorithm), None)
            if dropped:
                log.info(
                    "Model unloaded | tenant=%s algo=%s id=%s",
                    tenant_id, algorithm, dropped.model_id,
                )

    def unload_tenant(self, tenant_id: str) -> int:
        """
        Evict ALL in-memory models for *tenant_id* (e.g. on tenant deletion).

        Returns:
            Number of models evicted.
        """
        self._validate_tenant(tenant_id)
        with self._lock:
            keys_to_drop = [k for k in self._loaded if k[0] == tenant_id]
            for key in keys_to_drop:
                self._loaded.pop(key)
            # Also discard the cached registry instance
            self._registries.pop(tenant_id, None)

        log.info("All models evicted | tenant=%s count=%d", tenant_id, len(keys_to_drop))
        return len(keys_to_drop)

