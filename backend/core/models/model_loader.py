    def _load_record(
        self,
        tenant_id: str,
        record: ModelRecord,
        registry: ModelRegistry,
    ) -> LoadedModel:
        """Load a registry record into memory and refresh the tenant algorithm cache."""
        log.info(
            "Loading model | tenant=%s id=%s algo=%s version=%d",
            tenant_id, record.model_id, record.algorithm, record.version,
        )
        t0      = time.time()
        model   = registry.load(record.model_id)
        elapsed = time.time() - t0

        lm = LoadedModel(
            model=model,
            record=record,
            tenant_id=tenant_id,
            loaded_at=time.time(),
        )
        self._loaded[(tenant_id, record.algorithm)] = lm

        log.info(
            "Model ready | tenant=%s algo=%s id=%s version=%d elapsed=%.2fs",
            tenant_id, record.algorithm, record.model_id, record.version, elapsed,
        )
        return lm

